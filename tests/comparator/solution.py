#!/usr/bin/env python3
"""Write the Comparator solution, its checks and its config from
tests/comparator/Challenge.lean.

- Solution.lean states each challenge theorem in the same words and
  proves it with the law that the `-- law NAME` line above it names.
  Comparator requires the solution's statements to be the challenge's
  exactly, so they are copied, not retyped.
- Check.lean checks that each statement is the law's own
  (`#same_statement`), and prints each theorem's axioms (`#audit_axioms`),
  which tests/headline.sh requires to be Lean's standard three.
- comparator.json is `lake comparator`'s config (Lean v4.35):
  `lake comparator --config tests/comparator/comparator.json`.
- Weak.lean and comparator-weak.json are Comparator's negative control:
  the challenge with one statement weakened, which it must reject.
- own/<Group>Challenge.lean, own/<Group>Solution.lean and
  own-<group>.json: the laws that can be stated under their own names
  today, in groups whose challenges import none of their laws (OWN).

  tests/comparator/solution.py           write them all
  tests/comparator/solution.py --check   fail if any of them is stale
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODULE = "tests.comparator"
AXIOMS = ["propext", "Quot.sound", "Classical.choice"]
# Comparator's negative control: the challenge with one statement
# weakened, which Comparator must reject against the solution.
WEAK = ("t = u ∨ IsAdmin C ops c u", "t = u ∨ True")
WEAK_HEADER = '''/-
Generated by tests/comparator/solution.py from Challenge.lean: do not
edit by hand. Comparator's negative control: the challenge with
`removal_authorized` weakened to `t = u ∨ True`. `lake comparator
--config tests/comparator/comparator-weak.json` must reject it
(tests/headline.sh).
-/
'''
SOLUTION_HEADER = '''/-
Generated by tests/comparator/solution.py from Challenge.lean: do not
edit by hand. The solution for Comparator: each challenge theorem, in
the same words, proved by the app's own law. Check.lean checks that each
statement is the law's own.
-/
'''
CHECK_HEADER = '''/-
Generated by tests/comparator/solution.py from Challenge.lean: do not
edit by hand. Each theorem of the solution states its law word for word
(`#same_statement`: the file fails otherwise), and its axioms
(`#audit_axioms`), which tests/headline.sh requires to be standard.
-/
'''


def parts(challenge: str):
    """The challenge's imports, its body after `namespace Headline`, and
    its theorems with their laws."""
    head, sep, body = challenge.partition('\nnamespace Headline\n')
    if not sep:
        raise SystemExit('Challenge.lean: no `namespace Headline`')
    imports = [l for l in head.split('\n') if l.startswith('import ')]
    laws, law, out = [], None, []
    for line in body.split('\n'):
        m = re.match(r'-- law (\S+)$', line)
        if m:
            law = m.group(1)
        m = re.match(r'theorem (\w+)', line)
        if m:
            if law is None:
                raise SystemExit(f'Challenge.lean: theorem {m.group(1)} names no law')
            laws.append((m.group(1), law))
            law = None
        if line.strip() == 'sorry':
            if not laws:
                raise SystemExit('Challenge.lean: a sorry outside a theorem')
            line = line.replace('sorry', f'apply {laws[-1][1]} <;> assumption')
        out.append(line)
    return imports, out, laws


def files(challenge: str) -> dict:
    imports, body, laws = parts(challenge)
    solution = (SOLUTION_HEADER + '\n'.join(imports) + '\n\nnamespace Headline\n' +
                '\n'.join(body).rstrip('\n') + '\n')
    check = (CHECK_HEADER + f'import tests.SpecSurface\nimport {MODULE}.Solution\n\n' +
             '\n'.join(f'#same_statement Headline.{n} {l}' for n, l in laws) + '\n' +
             '\n'.join(f'#audit_axioms Headline.{n}' for n, _ in laws) + '\n')
    config = json.dumps({
        "challenge_module": f"{MODULE}.Challenge",
        "solution_module": f"{MODULE}.Solution",
        "theorem_names": [f"Headline.{n}" for n, _ in laws],
        "definition_names": [],
        "permitted_axioms": AXIOMS,
    }, indent=2) + '\n'
    if challenge.count(WEAK[0]) != 1:
        raise SystemExit(f'Challenge.lean: the control weakens `{WEAK[0]}`, which must occur once')
    body = challenge[challenge.index('\nimport ') + 1:] if challenge.startswith('/-') else challenge
    weak = WEAK_HEADER + body.replace(WEAK[0], WEAK[1])
    weak_config = config.replace(f'"{MODULE}.Challenge"', f'"{MODULE}.Weak"')
    return {'Solution.lean': solution, 'Check.lean': check, 'comparator.json': config,
            'Weak.lean': weak, 'comparator-weak.json': weak_config}


# Under the laws' own names. A challenge then cannot import the module
# that holds a law, or one that imports it (the name would be declared
# twice), so each group imports only modules that define what its
# statements name (`#challenge_imports` in tests/SpecSurface.lean finds
# them, and the laws that cannot be stated so yet). One group per
# challenge whose imports reach none of its laws' modules.
OWN = [
    ("Community",
     [("no_impersonation", "app.community.Proofs"),
      ("admission_needs_approval", "app.community.member.invite.Proofs"),
      ("removal_authorized", "app.community.member.Proofs"),
      ("connect_iff", "app.community.Proofs"),
      ("sealed_auth", "app.connection.Proofs"),
      ("select_tapped_dedupe", "app.community.Screen"),
      ("approveReq_ops", "app.community.Proofs")],
     ["app.community.Family", "app.community.Op", "engine.core.Codec", "engine.core.Core",
      "app.community.member.admin.Proofs", "app.community.Commands",
      "app.community.member.remove.Proofs", "engine.core.Model", "engine.core.Proofs",
      "engine.core.View", "app.connection.Commands", "app.connection.Family",
      "engine.core.Families", "engine.core.Held", "engine.sync.Sweep", "engine.wire.Node",
      "engine.wire.Noise", "app.community.member.join.accept.View",
      "app.community.key.wrap.Proofs"]),
    ("Agree", [("same_ops_same_verdicts", "engine.core.Termination")],
     ["engine.core.Core", "engine.core.Model", "engine.core.Proofs", "engine.core.Run"]),
    ("Cost", [("ingest_costs", "engine.core.IngestCost")],
     ["engine.core.Core", "engine.core.Cost", "engine.core.CostStore"]),
    ("Back", [("back_open", "app.Proofs")], ["app.Screen", "engine.renderer.Presentation"]),
]
OWN_HEADER = '''/-
Generated by tests/comparator/solution.py from Challenge.lean: do not
edit by hand. A Comparator challenge under the laws' own names ({group}):
the statements of Challenge.lean, each under the name of its law, with
`sorry`. It imports only modules that define what they name, none that
holds or imports one of these laws.
-/
'''
OWN_SOLUTION_HEADER = '''/-
Generated by tests/comparator/solution.py: do not edit by hand. The
solution to {group}Challenge: the modules that hold the laws.
-/
'''


def blocks(challenge: str) -> dict:
    """Each challenge theorem: its law, the `open`s around it, its lines."""
    out, opens, cur = {}, '', None
    for line in challenge.split('\n'):
        if line.startswith('open '):
            opens = line[5:]
        elif line == 'end':
            opens = ''
        m = re.match(r'-- law (\S+)$', line)
        if m:
            cur = {'law': m.group(1), 'opens': opens, 'lines': []}
        if cur is not None:
            cur['lines'].append(line)
            t = re.match(r'theorem (\w+)', line)
            if t:
                cur['name'] = t.group(1)
            if line.strip() == 'sorry':
                out[cur['name']] = cur
                cur = None
    return out


def own_files(challenge: str) -> dict:
    bs, out = blocks(challenge), {}
    for group, laws, imports in OWN:
        text = OWN_HEADER.format(group=group) + '\n'.join(f'import {m}' for m in imports) + '\n'
        for name, _ in laws:
            b = bs[name]
            lines = [b['lines'][0]] + ([f"open {b['opens']} in"] if b['opens'] else []) + [
                re.sub(r'^theorem \w+', f"theorem {b['law']}", l) for l in b['lines'][1:]]
            text += '\n' + '\n'.join(lines) + '\n'
        out[f'own/{group}Challenge.lean'] = text
        mods = sorted({m for _, m in laws})
        out[f'own/{group}Solution.lean'] = (OWN_SOLUTION_HEADER.format(group=group) +
                                            '\n'.join(f'import {m}' for m in mods) + '\n')
        out[f'own-{group.lower()}.json'] = json.dumps({
            "challenge_module": f"{MODULE}.own.{group}Challenge",
            "solution_module": f"{MODULE}.own.{group}Solution",
            "theorem_names": [bs[n]['law'] for n, _ in laws],
            "definition_names": [],
            "permitted_axioms": AXIOMS,
        }, indent=2) + '\n'
    return out


def main() -> int:
    challenge = (HERE / 'Challenge.lean').read_text()
    out = files(challenge) | own_files(challenge)
    if '--check' in sys.argv[1:]:
        stale = [name for name, text in out.items()
                 if not (HERE / name).exists() or (HERE / name).read_text() != text]
        if stale:
            print(f'tests/comparator: {", ".join(stale)} stale: run tests/comparator/solution.py',
                  file=sys.stderr)
            return 1
        return 0
    (HERE / 'own').mkdir(exist_ok=True)
    for name, text in out.items():
        (HERE / name).write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
