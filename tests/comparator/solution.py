#!/usr/bin/env python3
"""Write tests/comparator/Solution.lean from Challenge.lean (DRAFT).

The solution states each challenge theorem in the same words and proves
it with the law the `-- law NAME` line above it names. It then checks
that each statement is the law's own (`#same_statement`), and prints each
theorem's axioms (`#audit_axioms`), which tests/comparator/check.sh
requires to be Lean's standard three.

  tests/comparator/solution.py           write Solution.lean
  tests/comparator/solution.py --check   fail if Solution.lean is stale
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = '''/-
DRAFT, generated by tests/comparator/solution.py from Challenge.lean: do
not edit by hand. The solution for Comparator: each challenge theorem,
in the same words, proved by the app's own law. Its checks fail the file
if a statement is not the law's own (`#same_statement`); check.sh reads
the axioms (`#audit_axioms`).

  lake build SpecTools && lake env lean tests/comparator/Solution.lean
-/
'''


def solution(challenge: str) -> str:
    head, sep, body = challenge.partition('\nnamespace Headline\n')
    if not sep:
        raise SystemExit('Challenge.lean: no `namespace Headline`')
    imports = [l for l in head.split('\n') if l.startswith('import ')]
    laws = []
    lines = body.split('\n')
    law = None
    out = []
    for line in lines:
        m = re.match(r'-- law (\S+)$', line)
        if m:
            law = m.group(1)
        m = re.match(r'theorem (\w+)', line)
        if m:
            if law is None:
                raise SystemExit(f'Challenge.lean: theorem {m.group(1)} names no law')
            laws.append((m.group(1), law))
            law = None
        if line.strip() == 'sorry':
            if not laws:
                raise SystemExit('Challenge.lean: a sorry outside a theorem')
            line = line.replace('sorry', f'apply {laws[-1][1]} <;> assumption')
        out.append(line)
    checks = ['', '/-! ## Checks -/', '']
    checks += [f'#same_statement Headline.{n} {l}' for n, l in laws]
    checks += [f'#audit_axioms Headline.{n}' for n, _ in laws]
    return (HEADER + '\n'.join(['import tests.SpecSurface'] + imports) +
            '\n\nnamespace Headline\n' + '\n'.join(out).rstrip('\n') + '\n' + '\n'.join(checks) + '\n')


def main() -> int:
    text = solution((HERE / 'Challenge.lean').read_text())
    path = HERE / 'Solution.lean'
    if '--check' in sys.argv[1:]:
        if not path.exists() or path.read_text() != text:
            print('tests/comparator/Solution.lean is stale: run tests/comparator/solution.py', file=sys.stderr)
            return 1
        return 0
    path.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
