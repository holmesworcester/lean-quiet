#!/usr/bin/env python3
"""Generate the renderer's Unicode 16.0.0 Bidi_Class table, offline.

Assigned characters come from Python's UCD 16.0.0. Unassigned characters
use UAX #44's Bidi_Class defaults (including reserved RTL blocks and BN
noncharacters). No native Unicode library is called by the renderer.
"""
import pathlib
import unicodedata as u

assert u.unidata_version == '16.0.0', u.unidata_version
# The default ranges, also present in the local Perl UCD's To/Bc.pl.
defaults = [
    (0x0590,0x05ff,'R'), (0x0600,0x07bf,'AL'), (0x07c0,0x085f,'R'),
    (0x0860,0x08ff,'AL'), (0x20a0,0x20cf,'ET'), (0xfb1d,0xfb4f,'R'),
    (0xfb50,0xfdcf,'AL'), (0xfdf0,0xfdff,'AL'), (0xfe70,0xfeff,'AL'),
    (0x10800,0x10cff,'R'), (0x10d00,0x10d3f,'AL'), (0x10d40,0x10ebf,'R'),
    (0x10ec0,0x10eff,'AL'), (0x10f00,0x10f2f,'R'), (0x10f30,0x10f6f,'AL'),
    (0x10f70,0x10fff,'R'), (0x1e800,0x1ec6f,'R'), (0x1ec70,0x1ecbf,'AL'),
    (0x1ecc0,0x1ecff,'R'), (0x1ed00,0x1ed4f,'AL'), (0x1ed50,0x1edff,'R'),
    (0x1ee00,0x1eeff,'AL'), (0x1ef00,0x1efff,'R')]
def cls(c):
    assigned = u.bidirectional(chr(c))
    if assigned:
        return assigned
    if (c & 0xffff >= 0xfffe or 0xfdd0 <= c <= 0xfdef or 0xe0000 <= c <= 0xe0fff
            or c == 0x2065 or 0xfff0 <= c <= 0xfff8):
        return 'BN'
    return next((v for a,b,v in defaults if a <= c <= b), 'L')

ranges = []
for c in range(0x110000):
    v = cls(c)
    if ranges and ranges[-1][1] == v:
        ranges[-1] = (c, v)
    else:
        ranges.append((c, v))

def tree(rs, indent='  '):
    if len(rs) == 1:
        return '.' + rs[0][1].lower()
    mid = len(rs)//2
    return (f'if c ≤ 0x{rs[mid-1][0]:X} then\n{indent}  ' + tree(rs[:mid],indent+'  ')
            + f'\n{indent}else\n{indent}  ' + tree(rs[mid:],indent+'  '))

out = ['/-\nUnicode 16.0.0 Bidi_Class, generated by tools/bidi_table.py from the local\nPython UCD and UAX #44 defaults. Balanced searches have bounded depth;\nclassification is constant time per code point. No laws in this data module.\n-/\nnamespace Text.Bidi\n',
       'inductive Class where\n  | l | r | al | en | an | es | et | cs | nsm | bn | b | s | ws | on\n  | lre | rle | lro | rlo | pdf | lri | rli | fsi | pdi\n  deriving BEq, DecidableEq, Inhabited, Repr\n']
chunks = [ranges[i:i+64] for i in range(0,len(ranges),64)]
for i, rs in enumerate(chunks):
    out.append(f'private def part{i} (c : UInt32) : Class :=\n  {tree(rs)}\n')
def outer(xs, indent='  '):
    if len(xs)==1:
        return f'part{xs[0][0]} c'
    mid=len(xs)//2
    return f'if c ≤ 0x{xs[mid-1][1]:X} then\n{indent}  '+outer(xs[:mid],indent+'  ')+f'\n{indent}else\n{indent}  '+outer(xs[mid:],indent+'  ')
out.append('def classOf (c : UInt32) : Class :=\n  '+outer([(i,rs[-1][0]) for i,rs in enumerate(chunks)])+'\n\nend Text.Bidi\n')
pathlib.Path('engine/renderer/bidi/Class.lean').write_text('\n'.join(out))
print(f'Unicode {u.unidata_version}: {len(ranges)} ranges, {len(chunks)} bounded definitions')
