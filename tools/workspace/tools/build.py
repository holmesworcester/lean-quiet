#!/usr/bin/env python3
"""Compile actual Lean scalar exports to WASM and bundle the browser workspace."""
from pathlib import Path
import hashlib, json, os, re, shutil, subprocess
ROOT = Path(__file__).resolve().parents[1]
BUILD, DIST = ROOT / 'build', ROOT / 'dist'
BUILD.mkdir(exist_ok=True)
DIST.mkdir(exist_ok=True)
repo = ROOT.parents[1]
# The op tree on disk, with what is planned. The checked-in tree must match it.
subprocess.run(['python3', str(ROOT / 'tools/plan.py'), '--out', str(DIST / 'plan.json'),
                '--check-tree', str(repo / 'docs/OP_TREE.txt')], check=True)
shutil.copyfile(repo / 'docs/OP_TREE.txt', DIST / 'op-tree.txt')
lean = os.environ.get('LEAN') or shutil.which('lean')
if not lean:
    candidate = Path('/mnt/storage/elan/toolchains/leanprover--lean4---v4.34.0/bin/lean')
    if candidate.exists(): lean = str(candidate)
if not lean: raise SystemExit('Lean 4.34.0 is required; set LEAN or put lean on PATH.')
version = subprocess.check_output([lean, '--version'], text=True).strip()
if '4.34.0' not in version: raise SystemExit(f'Expected Lean 4.34.0, got {version}')
prefix = Path(subprocess.check_output([lean, '--print-prefix'], text=True).strip())
include = BUILD / 'include' / 'lean'
include.mkdir(parents=True, exist_ok=True)
for name in ('lean.h', 'version.h'):
    shutil.copyfile(prefix / 'include' / 'lean' / name, include / name)
# No heap is reachable from these scalar exports. Use upstream inline arithmetic,
# disable the native allocator, and let the linker discard boxed entry points.
(include / 'config.h').write_text('#pragma once\n#include <lean/version.h>\n#define LEAN_IS_STAGE0 0\n')
result = subprocess.run([lean, '-R', '.', '-c', str(BUILD / 'kernel.c'), 'lean/Kernel.lean'], cwd=ROOT, capture_output=True, text=True)
(BUILD / 'proof-check.log').write_text(result.stdout + result.stderr)
if result.returncode: raise SystemExit(result.stdout + result.stderr)
if 'sorryAx' in result.stdout: raise SystemExit('Proof contains sorryAx')
parity_source = (ROOT / 'lean/Kernel.lean').read_text() + '''
def main : IO Unit := do
  for p in [0:2] do
    for v in [0:2] do
      for m in [0:2] do
        for c in [0:2] do
          for s in [0:2] do
            IO.println s!"CASE|validate|{p},{v},{m},{c},{s}|{Workspace.validate p.toUInt32 v.toUInt32 m.toUInt32 c.toUInt32 s.toUInt32}"
  for dark in [0:2] do
    for x in [0, 16, 30, 52, 80, 150, 270, 280, 303] do
      for y in [0, 57, 74, 100, 135, 141, 173, 234, 240, 300, 335, 350, 370, 397] do
        IO.println s!"CASE|pixel|{x},{y},{dark},2857307|{Workspace.pixel x.toUInt32 y.toUInt32 dark.toUInt32 2857307}"
'''
(BUILD / 'Parity.lean').write_text(parity_source)
parity = subprocess.check_output([lean, '-R', '.', '--run', 'build/Parity.lean'], cwd=ROOT, text=True)
(BUILD / 'native-parity.txt').write_text(parity)
exports = ['quiet_validate', 'quiet_theme', 'quiet_color', 'quiet_pixel']
subprocess.run(['clang', '--target=wasm32', '-ffreestanding', '-nostdlib', '-O2', '-I', str(BUILD / 'include'), str(BUILD / 'kernel.c'), '-Wl,--no-entry', '-Wl,--gc-sections', *['-Wl,--export='+e for e in exports], '-o', str(DIST / 'kernel.wasm')], check=True)
for name in ('index.html', 'style.css'):
    shutil.copyfile(ROOT / 'src' / name, DIST / name)
shutil.copytree(ROOT / 'src' / 'fonts', DIST / 'fonts', dirs_exist_ok=True)
for name in ('app.js','prover.js'):
    subprocess.run([str(ROOT / 'node_modules' / '.bin' / 'esbuild'), str(ROOT / 'src' / name), '--bundle', '--format=esm', '--target=es2022', '--outfile='+str(DIST / name)], check=True)
source = (ROOT / 'lean/Kernel.lean').read_text()
sha = hashlib.sha256(source.encode()).hexdigest()
(DIST / 'Kernel.lean').write_text(source)
# Publish an explicit source allowlist; never expose the repository filesystem.
paths = ['tools/workspace/lean/Kernel.lean', 'tools/workspace/src/state.js',
         'docs/OP_WORKSPACE_REQUIREMENTS.md', 'docs/LAYOUT.md',
         'docs/security/auditician/THREATMODEL.md', 'docs/security/auditician/ICTM-REVIEW-DECISIONS.md']
files = {}
for path in paths:
    text = (repo / path).read_text()
    declarations = []
    for number, line in enumerate(text.splitlines(), 1):
        match = re.match(r'^(?:@\[.*?\] )?(?:(?:export|async|partial) )?(def|structure|inductive|abbrev|theorem|function) ([\w.]+)', line)
        if match:
            declarations.append({'name': match[2], 'kind': match[1], 'line': number})
    files[path] = {'text': text, 'sha256': hashlib.sha256(text.encode()).hexdigest(), 'declarations': declarations}
catalog = []
# A fresh workspace checkout must not require native font/emoji downloads.
# Snapshot generated by tools/picker.py from libquiet 38a909706:app/src/emoji-data.json,
# the same input pinned by tools/fetch_assets.sh.
catalog_path = repo / 'assets/picker.txt'
if not catalog_path.exists(): catalog_path = ROOT / 'fixtures/picker.txt'
for line in catalog_path.read_text().splitlines():
    parts = line.split('\t')
    if len(parts) == 5:
        group, emoji, skins, label, tags = parts
        catalog.append({'group': int(group), 'emoji': emoji, 'skins': skins.split(), 'label': label, 'tags': tags})
# The Lean sources outside app/ (the plan carries app/), one file each, fetched when a page shows them.
tracked = subprocess.check_output(['git', 'ls-files', '*.lean'], cwd=repo, text=True).split()
shutil.rmtree(DIST / 'src', ignore_errors=True)
for path in tracked:
    if path.split('/')[0] in ('engine', 'platforms', 'tests') or path in ('Main.lean', 'Quiet.lean'):
        out = DIST / 'src' / path
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(repo / path, out)
index_bytes = json.dumps({'files': files, 'catalog': catalog}, ensure_ascii=False).encode()
(DIST / 'sources.json').write_bytes(index_bytes)
index_sha = hashlib.sha256(index_bytes).hexdigest()
(DIST / 'evidence.json').write_text(json.dumps({'lean': version, 'sourceSha256': sha, 'wasmSha256': hashlib.sha256((DIST/'kernel.wasm').read_bytes()).hexdigest(), 'proofLog': result.stdout, 'sourceIndexSha256': index_sha, 'planSha256': hashlib.sha256((DIST / 'plan.json').read_bytes()).hexdigest(), 'scope': 'Prototype scalar kernel only; not Quiet production validation.'}, indent=2))
(DIST / '_headers').write_text('/*\n  Cross-Origin-Opener-Policy: same-origin\n  Cross-Origin-Embedder-Policy: require-corp\n')
print(f'Built Lean WASM: {(DIST/"kernel.wasm").stat().st_size} bytes; source {sha[:12]}')
